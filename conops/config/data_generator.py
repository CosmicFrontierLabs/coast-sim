from collections.abc import Mapping

from pydantic import Field, field_validator

from ..common.enums import ACSMode
from ._base import ConfigModel


class DataMixin(ConfigModel):
    """
    Science data terms: what collecting science generates.

    Shared by :class:`DataGeneration`, which an instrument has, and
    :class:`ScienceData`, which a target uses to set its own.

    Attributes:
        rate_gbps (float): Data generation rate in Gigabits per second while
            collecting. Defaults to 0.0 (no data generation).
        per_observation_gb (float): Fixed data generated by each observation in
            Gb, such as calibration frames or headers, in addition to the
            rate. Defaults to 0.0.
    """

    rate_gbps: float = Field(
        default=0.0, ge=0.0, description="Data generation rate in Gbps while collecting"
    )
    per_observation_gb: float = Field(
        default=0.0,
        ge=0.0,
        description="Fixed data generated per observation in Gb",
    )


class ScienceData(DataMixin):
    """
    A target's science data for one instrument.

    What an observation generates depends on what is observed, so a target can
    set, for each instrument, the science data that instrument generates while
    observing it. It replaces the instrument's ``rate_gbps`` and
    ``per_observation_gb``; the instrument's housekeeping data is unchanged.

    Example:
        >>> # A bright source: 0.3 Gbps in the camera while observing it
        >>> science_data = {"camera": ScienceData(rate_gbps=0.3)}
    """


class HousekeepingData(ConfigModel):
    """
    Housekeeping data: engineering telemetry such as temperatures, voltages,
    attitude and status, generated at all times whatever is observed.

    The spacecraft bus generates only this; an instrument generates it as
    well as science data (see :class:`DataGeneration`). The rate can depend on
    the ACS mode, the way :class:`~conops.config.PowerDraw` does for power.

    Attributes:
        housekeeping_rate_gbps (float): Rate generated at all times, in Gbps.
        housekeeping_rate_mode (dict[ACSMode, float]): Rate in Gbps in
            particular ACS modes, replacing ``housekeeping_rate_gbps``. Modes may
            be given by name or number.

    Example:
        >>> # 1 Mbps of housekeeping, 4 Mbps of diagnostics in safe mode
        >>> housekeeping = HousekeepingData(
        ...     housekeeping_rate_gbps=0.001, housekeeping_rate_mode={"SAFE": 0.004}
        ... )
        >>> housekeeping.data_generated(60, mode=ACSMode.SAFE)
        0.24
    """

    housekeeping_rate_gbps: float = Field(
        default=0.0,
        ge=0.0,
        description="Data generation rate in Gbps at all times, such as housekeeping",
    )
    housekeeping_rate_mode: dict[ACSMode, float] = Field(
        default_factory=dict,
        description="Housekeeping data generation rate in Gbps in particular ACS modes",
    )

    @field_validator("housekeeping_rate_mode", mode="before")
    @classmethod
    def _mode_names(cls, value: object) -> object:
        """Accept ACS modes by name as well as number."""
        if not isinstance(value, Mapping):
            return value
        return {
            ACSMode[key]
            if isinstance(key, str) and key in ACSMode.__members__
            else key: rate
            for key, rate in value.items()
        }

    @field_validator("housekeeping_rate_mode")
    @classmethod
    def _rates_not_negative(cls, value: dict[ACSMode, float]) -> dict[ACSMode, float]:
        if any(rate < 0 for rate in value.values()):
            raise ValueError("housekeeping rates must not be negative")
        return value

    def housekeeping_rate(self, mode: ACSMode | None = None) -> float:
        """Housekeeping data generation rate in Gbps in an ACS mode.

        Args:
            mode: ACS mode, or None for the nominal rate.
        """
        if mode is None:
            return self.housekeeping_rate_gbps
        return self.housekeeping_rate_mode.get(mode, self.housekeeping_rate_gbps)

    def data_generated(
        self, duration_seconds: float, *, mode: ACSMode | None = None
    ) -> float:
        """Data generated over an interval.

        Args:
            duration_seconds: Length of the interval in seconds.
            mode: ACS mode during the interval; None for the nominal rate.

        Returns:
            float: Data generated in Gigabits.
        """
        return self.housekeeping_rate(mode) * duration_seconds


class DataGeneration(HousekeepingData, DataMixin):
    """
    Data generated by an instrument.

    An instrument generates housekeeping data at all times (see
    :class:`HousekeepingData`), and science data
    (``rate_gbps`` and ``per_observation_gb``) only while science is
    collected. A target can replace an instrument's science data with its own.

    Example:
        >>> # 0.5 Gbps while collecting, 1 Mbps of housekeeping, 10 Mbps in safe mode
        >>> data = DataGeneration(
        ...     rate_gbps=0.5,
        ...     housekeeping_rate_gbps=0.001,
        ...     housekeeping_rate_mode={"SAFE": 0.01},
        ... )
        >>> data.data_generated(60)  # one 60 s observation
        30.06
    """

    def data_generated(
        self,
        duration_seconds: float,
        *,
        mode: ACSMode | None = None,
        collection_seconds: float | None = None,
        observations: int = 1,
        science: ScienceData | None = None,
    ) -> float:
        """Data generated over an interval.

        With only a duration, this is one observation collecting for all of it.

        Args:
            duration_seconds: Length of the interval in seconds.
            mode: ACS mode during the interval, which sets the housekeeping
                rate; None for the nominal rate.
            collection_seconds: Seconds of science collected in the interval;
                None for all of it.
            observations: Observations that began collecting in the interval,
                each adding ``per_observation_gb``.
            science: The observed target's science data for this instrument,
                replacing ``rate_gbps`` and ``per_observation_gb``.

        Returns:
            float: Data generated in Gigabits.
        """
        collected = self if science is None else science
        if collection_seconds is None:
            collection_seconds = duration_seconds
        return (
            super().data_generated(duration_seconds, mode=mode)
            + collected.rate_gbps * collection_seconds
            + collected.per_observation_gb * observations
        )
